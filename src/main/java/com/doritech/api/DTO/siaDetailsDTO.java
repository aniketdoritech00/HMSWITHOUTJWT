package com.doritech.api.DTO;

public class siaDetailsDTO {

	private String branchName;
	private String branchAddress;
	private String branchIfsc;
	private String branchEmail;
	private String branchNumber; 
	private String devicePanelSerialNo;
	private String deviceType;
	
	public String getBranchName() {
		return branchName;
	}
	public void setBranchName(String branchName) {
		this.branchName = branchName;
	}
	public String getBranchAddress() {
		return branchAddress;
	}
	public void setBranchAddress(String branchAddress) {
		this.branchAddress = branchAddress;
	}
	public String getBranchIfsc() {
		return branchIfsc;
	}
	public void setBranchIfsc(String branchIfsc) {
		this.branchIfsc = branchIfsc;
	}
	public String getBranchNumber() {
		return branchNumber;
	}
	public void setBranchNumber(String branchNumber) {
		this.branchNumber = branchNumber;
	}
	public String getDevicePanelSerialNo() {
		return devicePanelSerialNo;
	}
	public void setDevicePanelSerialNo(String devicePanelSerialNo) {
		this.devicePanelSerialNo = devicePanelSerialNo;
	}
	public String getDeviceType() {
		return deviceType;
	}
	public void setDeviceType(String deviceType) {
		this.deviceType = deviceType;
	}
	public String getBranchEmail() {
		return branchEmail;
	}
	public void setBranchEmail(String branchEmail) {
		this.branchEmail = branchEmail;
	}
	  
	
}